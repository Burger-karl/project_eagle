"""
Regression test for the Sage 200 `since` filter.

The query used to read:
    WHERE ar.Debit > 0 OR ar.Credit > 0 AND ar.TxDate > ?
SQL evaluates AND before OR, so every debit row (every invoice) came back whatever
the date, and only credit rows were date-filtered.

This runs the real SQL generated by Sage200ODBCClient against an in-memory SQLite
copy of the two tables it reads. SQLite has no TOP, so that one keyword is rewritten.
"""
import re
import sqlite3
from contextlib import contextmanager
from datetime import datetime

import pytest

from apps.core.models import ClientCompany
from apps.sage200.odbc_client import Sage200ODBCClient


class _TopToLimit:
    """Wraps a sqlite cursor so T-SQL `SELECT TOP n` runs on SQLite."""

    def __init__(self, cur):
        self._cur = cur

    def execute(self, sql, params=()):
        top = re.search(r"SELECT TOP (\d+)", sql)
        if top:
            sql = sql.replace(top.group(0), "SELECT") + f" LIMIT {top.group(1)}"
        self._cur.execute(sql, params)

    def __getattr__(self, name):
        return getattr(self._cur, name)


@pytest.fixture
def sage():
    db = sqlite3.connect(":memory:")
    db.executescript(
        """
        CREATE TABLE Client (DCLink INT, Account TEXT, Name TEXT, Physical1 TEXT, Physical2 TEXT,
            Physical3 TEXT, Physical4 TEXT, Physical5 TEXT, PhysicalPC TEXT, Email TEXT);
        CREATE TABLE PostAR (AutoIdx INT, TxDate TEXT, DTStamp TEXT, Id TEXT, TrCodeID INT,
            Reference TEXT, cReference2 TEXT, AccountLink INT, Debit REAL, Credit REAL,
            Tax_Amount REAL, fExchangeRate REAL, iCurrencyID INT, InvNumKey INT);
        INSERT INTO Client (DCLink, Account, Name) VALUES (1, 'CUS001', 'Acme Customer');
        """
    )
    rows = [  # AutoIdx, TxDate, Id, Debit, Credit
        (1, "2026-01-10", "Inv", 1000.0, 0.0),    # old invoice
        (2, "2026-08-15", "Inv", 2000.0, 0.0),    # old invoice
        (3, "2026-09-05", "Inv", 3000.0, 0.0),    # new invoice
        (4, "2026-08-20", "CrN", 0.0, 400.0),     # old credit note
        (5, "2026-09-10", "CrN", 0.0, 500.0),     # new credit note
        (6, "2026-09-12", "Zero", 0.0, 0.0),      # neither debit nor credit: never wanted
    ]
    for i, day, code, dr, cr in rows:
        db.execute(
            "INSERT INTO PostAR VALUES (?,?,?,?,38,?,'',1,?,?,0,1,0,NULL)",
            (i, day, day + " 09:00:00", code, f"REF{i}", dr, cr),
        )
    company = ClientCompany(name="Test", mssql_server="s", mssql_database="d")
    client = Sage200ODBCClient(company)

    @contextmanager
    def connection():
        class Conn:
            def cursor(self_inner):
                return _TopToLimit(db.cursor())
        yield Conn()

    client.get_connection = connection
    return client


def ids(rows):
    return sorted(r["invoice_id"] for r in rows)


def test_without_since_every_debit_and_credit_row_is_returned(sage):
    assert ids(sage.get_new_invoices()) == [1, 2, 3, 4, 5]


def test_since_filters_invoices_as_well_as_credit_notes(sage):
    rows = sage.get_new_invoices(since=datetime(2026, 9, 1))
    assert ids(rows) == [3, 5]          # the old invoices 1 and 2 must NOT come back


def test_since_in_the_future_returns_nothing(sage):
    assert sage.get_new_invoices(since=datetime(2030, 1, 1)) == []
